static const mono_font_metrics_t font5x6_info =
{
    FONT5X6_WIDTH,
    FONT5X6_HEIGHT,
    6u,
    7u
};

const mono_font_metrics_t *font5x6_metrics(void)
{
    return &font5x6_info;
}

const uint8_t *font5x6_glyph(char c)
{
    if ((c >= '0') && (c <= '9'))
    {
        return font5x6_data[(uint32_t)(c - '0')];
    }

    if ((c >= 'A') && (c <= 'Z'))
    {
        return font5x6_data[10u + (uint32_t)(c - 'A')];
    }

    return font5x6_data[36u];
}
