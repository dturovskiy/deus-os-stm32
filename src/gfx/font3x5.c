#include <stdint.h>
#include "gfx/font3x5.h"

/*
 * Each byte is one 3-pixel row.
 * Bit 2 is left, bit 0 is right.
 */
static const uint8_t font3x5_glyph_data[11][5] =
{
    { 0x7u, 0x5u, 0x5u, 0x5u, 0x7u }, /* 0 */
    { 0x2u, 0x6u, 0x2u, 0x2u, 0x7u }, /* 1 */
    { 0x7u, 0x1u, 0x7u, 0x4u, 0x7u }, /* 2 */
    { 0x7u, 0x1u, 0x7u, 0x1u, 0x7u }, /* 3 */
    { 0x5u, 0x5u, 0x7u, 0x1u, 0x1u }, /* 4 */
    { 0x7u, 0x4u, 0x7u, 0x1u, 0x7u }, /* 5 */
    { 0x7u, 0x4u, 0x7u, 0x5u, 0x7u }, /* 6 */
    { 0x7u, 0x1u, 0x2u, 0x2u, 0x2u }, /* 7 */
    { 0x7u, 0x5u, 0x7u, 0x5u, 0x7u }, /* 8 */
    { 0x7u, 0x5u, 0x7u, 0x1u, 0x7u }, /* 9 */
    { 0x0u, 0x2u, 0x0u, 0x2u, 0x0u }, /* colon */
};

const uint8_t *font3x5_glyph(char c)
{
    if ((c >= '0') && (c <= '9'))
    {
        return font3x5_glyph_data[(uint32_t)(c - '0')];
    }
    if (c == ':')
    {
        return font3x5_glyph_data[10u];
    }
    return (const uint8_t *)0;
}
