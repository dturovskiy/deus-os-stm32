static const mono_font_metrics_t font5x7_info =
{
    FONT5X7_WIDTH,
    FONT5X7_HEIGHT,
    6u,
    8u
};

const mono_font_metrics_t *font5x7_metrics(void)
{
    return &font5x7_info;
}

const uint8_t *font5x7_glyph(char c)
{
    if ((c >= '0') && (c <= '9'))
    {
        return font5x7_data[(uint32_t)(c - '0')];
    }

    if ((c >= 'A') && (c <= 'Z'))
    {
        return font5x7_data[10u + (uint32_t)(c - 'A')];
    }

    return font5x7_data[36u];
}
